"""Day 4 (Member B): exports. Both functions return bytes, so Streamlit can pass them straight to st.download_button.

Each test is a dict: id, level, tier, clause, equipment, status, steps (";"-separated), instruments, acceptance, reason.
`decisions` maps test id -> "Approved" / "Rejected" (from the approvals table; Day 5 wires this in).
"""
import io

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

FILLS = {"Approved": "E3F6EC", "Rejected": "FDEEEE", "Blocked": "FFF4E0"}


def build_traceability_xlsx(tests, decisions=None, no_test_clauses=()):
    """Sheet 1: clause -> test -> result -> sign-off. Sheet 2: clauses that still have no test."""
    decisions = decisions or {}
    wb = Workbook()
    ws = wb.active
    ws.title = "Traceability"
    head = ["Clause", "Test ID", "Level", "Tier", "Equipment", "Acceptance criteria", "Status", "Sign-off"]
    ws.append(head)
    for t in sorted(tests, key=lambda x: (x["clause"], x["level"], x["id"])):
        sign = decisions.get(t["id"], "")
        ws.append([t["clause"], t["id"], t["level"], t["tier"], t.get("equipment", ""), t.get("acceptance", ""),
                   sign or t.get("status", ""), sign])
        if (sign or t.get("status")) in FILLS:
            ws.cell(ws.max_row, 7).fill = PatternFill("solid", fgColor=FILLS[sign or t["status"]])
    for c in ws[1]:
        c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="1570EF")
    widths = [10, 12, 8, 8, 14, 44, 12, 12]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    gap = wb.create_sheet("Clauses without a test")
    gap.append(["Clause"])
    for c in no_test_clauses:
        gap.append([c])
    gap["A1"].font = Font(bold=True)
    gap.column_dimensions["A"].width = 18
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build_test_package_docx(tests, title="Commissioning test package"):
    """One section per test: steps, instruments, acceptance criteria, why this level, cited clause."""
    from docx import Document  # python-docx
    doc = Document()
    doc.add_heading(title, 0)
    doc.add_paragraph("Draft generated by DC Copilot. Every test must be reviewed and approved by an engineer.")
    for t in tests:
        doc.add_heading(f"{t['id']}  (Level {t['level']}, Tier {t['tier']})", 2)
        doc.add_paragraph(f"Cited clause: {t['clause']}   Equipment: {t.get('equipment', '-')}")
        doc.add_paragraph("Steps", style="Heading 3")
        steps = t.get("steps", "")
        for step in (steps if isinstance(steps, list) else str(steps).split(";")):
            if str(step).strip():
                doc.add_paragraph(str(step).strip(), style="List Number")
        doc.add_paragraph(f"Instruments: {t.get('instruments', '-')}")
        doc.add_paragraph(f"Acceptance criteria: {t.get('acceptance', '-')}")
        doc.add_paragraph(f"Why this level: {t.get('reason', '-')}")
        doc.add_paragraph("Engineer sign-off: ____________________   Date: ____________")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
